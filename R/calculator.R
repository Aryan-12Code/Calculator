#' Add two numbers
#' @export
add <- function(a, b) {
  return(a + b)
}

#' Subtract two numbers
#' @export
subtract <- function(a, b) {
  return(a - b)
}

#' Multiply two numbers
#' @export
multiply <- function(a, b) {
  return(a * b)
}

#' Divide two numbers
#' @export
divide <- function(a, b) {
  return(a / b)
}

#' Square a number
#' @export
square <- function(a) {
  a^2
}

#' Cube a number
#' @export
cube <- function(a) {
  a^3
}
